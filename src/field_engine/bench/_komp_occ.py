#!/usr/bin/env python3
"""Benchmark component: the B-rep side (OCCT through OCP/build123d).

Declared parts, both generated by this repository and written to STEP under bench/artifacts/:
S = the holed plate from `examples/parts/holed_plate_v1.py`, M = the recipe bracket from
`examples/parts/bracket_part_v1.py` at its declared theta. Measured: STEP export and read (s),
tessellation (BRepMesh_IncrementalMesh, deflection 0.5 mm, angle 0.5 rad) in triangles/s, and thread
scaling 1/2/4 through OSD_ThreadPool plus InParallel, which is OCCT's own pool and is not steered by
taskset or OMP. Correctness: a build123d box minus a through cylinder, and a sphere, against the
closed form -- the SAME box-minus-cylinder reference the field kernel uses, so two kernels share one
reference. Determinism: two tessellations give the same triangle count and the same vertex hash.
Writes bench/artifacts/_parts/occ_cad.json.
"""
import math
import os
import sys
import time

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import _bench_common as BC  # noqa: E402

SRC, ROOT = BC.repo_paths()
sys.path.insert(0, os.path.join(SRC, "loop"))
SNABB = BC.snabb()
STEP_DIR = os.path.join(BC.ARTIFACTS, "step")

from OCP.STEPControl import STEPControl_Reader  # noqa: E402
from OCP.BRepMesh import BRepMesh_IncrementalMesh  # noqa: E402
from OCP.IMeshTools import IMeshTools_Parameters  # noqa: E402
from OCP.OSD import OSD_ThreadPool  # noqa: E402
from OCP.TopExp import TopExp_Explorer  # noqa: E402
from OCP.TopAbs import TopAbs_FACE  # noqa: E402
from OCP.TopoDS import TopoDS  # noqa: E402
from OCP.BRep import BRep_Tool  # noqa: E402
from OCP.TopLoc import TopLoc_Location  # noqa: E402
from OCP.BRepTools import BRepTools  # noqa: E402

DEFL, ANG = 0.5, 0.5
BRACKET_THETA = {"plate_w": 150.0, "plate_h": 100.0, "thk": 10.0, "hole_d": 9.0}
SIZES = [("S", "holed_plate"), ("M", "bracket_v1")] if not SNABB else [("S", "holed_plate")]


def _bygg_step(namn):
    """Builds the declared part and exports it to STEP under bench/artifacts/step/.

    The part is rebuilt on every call, so the reported build-and-export time is measured and not the
    cost of finding a file from an earlier run."""
    os.makedirs(STEP_DIR, exist_ok=True)
    path = os.path.join(STEP_DIR, f"{namn}.step")
    from build123d import export_step
    if namn == "holed_plate":
        import holed_plate_v1 as PLATE
        solid = PLATE.build()
    elif namn == "bracket_v1":
        import bracket_part_v1 as BR
        solid = BR.build(BRACKET_THETA)
    else:
        raise KeyError(namn)
    export_step(solid, path)
    return path


def _read(path):
    r = STEPControl_Reader()
    st = r.ReadFile(path)
    r.TransferRoots()
    return r.OneShape(), int(st)


def _n_faces(shape):
    n = 0
    ex = TopExp_Explorer(shape, TopAbs_FACE)
    while ex.More():
        n += 1
        ex.Next()
    return n


def _tess(shape, n_threads):
    BRepTools.Clean_s(shape)  # force a new tessellation; otherwise it is cached in the B-rep
    OSD_ThreadPool.DefaultPool_s(n_threads).Init(n_threads)
    prm = IMeshTools_Parameters()
    prm.Deflection = DEFL
    prm.Angle = ANG
    prm.InParallel = n_threads > 1
    t0 = time.perf_counter()
    BRepMesh_IncrementalMesh(shape, prm)
    t = time.perf_counter() - t0
    n_tri, verts = 0, []
    ex = TopExp_Explorer(shape, TopAbs_FACE)
    while ex.More():
        loc = TopLoc_Location()
        tri = BRep_Tool.Triangulation_s(TopoDS.Face_s(ex.Current()), loc)
        if tri is not None:
            n_tri += tri.NbTriangles()
            verts.append(tri.NbNodes())
        ex.Next()
    return t, n_tri, int(sum(verts))


def del_storlekar():
    rows = []
    for lbl, namn in SIZES:
        t0 = time.perf_counter()
        path = _bygg_step(namn)
        t_export = time.perf_counter() - t0
        t0 = time.perf_counter()
        shape, st = _read(path)
        t_read = time.perf_counter() - t0
        nf = _n_faces(shape)
        t_tess, n_tri, n_v = _tess(shape, 4)
        rad = dict(label=lbl, del_namn=namn, fil_MB=os.path.getsize(path) / 1e6,
                   t_step_bygg_export_s=t_export, t_step_read_s=t_read, n_faces=nf,
                   t_tessellering_4trad_s=t_tess, n_tris=n_tri, n_verts=n_v,
                   trianglar_per_s=n_tri / max(t_tess, 1e-9), faces_per_s_read=nf / max(t_read, 1e-9),
                   deflection_mm=DEFL, vinkel_rad=ANG, rss_peak_mb_hittills=BC.rss_peak_mb())
        sk = []
        for n in (1, 2, 4):
            t_n, n_tri_n, _ = _tess(shape, n)
            sk.append(dict(n_tradar=n, t_s=t_n, n_tris=n_tri_n))
        for r in sk:
            r["speedup_vs_1"] = sk[0]["t_s"] / r["t_s"]
        rad["tradskalning"] = sk
        rows.append(rad)
    return dict(rader=rows)


def del_korrekthet():
    from build123d import Box, Cylinder, Sphere
    hx, hy, hz, r = 20.0, 15.0, 10.0, 6.0
    va = 8 * hx * hy * hz - math.pi * r * r * 2 * hz
    t0 = time.perf_counter()
    solid = Box(2 * hx, 2 * hy, 2 * hz) - Cylinder(r, 2 * hz + 2)
    t_bool = time.perf_counter() - t0
    t, _ = BC.timeit(lambda: Box(2 * hx, 2 * hy, 2 * hz) - Cylinder(r, 2 * hz + 2), n_reps=5)
    v = float(solid.volume)
    sp = Sphere(20.0)
    vs, vsa = float(sp.volume), 4.0 / 3.0 * math.pi * 20.0 ** 3
    return dict(box_minus_cyl_volym_mm3=v, analytisk_mm3=va, rel_fel=abs(v - va) / va,
                t_boolean_forsta_s=t_bool, t_boolean_p50_s=t["p50_s"], t_boolean_p95_s=t["p95_s"],
                sfar_volym_mm3=vs, sfar_analytisk_mm3=vsa, sfar_rel_fel=abs(vs - vsa) / vsa,
                GRON=bool(abs(v - va) / va < 1e-6 and abs(vs - vsa) / vsa < 1e-6),
                not_="the same box-minus-cylinder reference the field kernel's test field uses: "
                     "two kernels, one reference")


def del_determinism():
    path = _bygg_step(SIZES[-1][1])
    shape, _ = _read(path)
    hs = []
    for _ in range(2):
        _tess(shape, 4)
        ex = TopExp_Explorer(shape, TopAbs_FACE)
        pts = []
        while ex.More():
            loc = TopLoc_Location()
            tri = BRep_Tool.Triangulation_s(TopoDS.Face_s(ex.Current()), loc)
            if tri is not None:
                pts.extend([(tri.Node(i).X(), tri.Node(i).Y(), tri.Node(i).Z()) for i in range(1, tri.NbNodes() + 1)])
            ex.Next()
        hs.append((len(pts), BC.sha_arr(np.array(pts, dtype=np.float64))))
    return dict(del_namn=SIZES[-1][1], run1=hs[0], run2=hs[1], bit_identisk=hs[0] == hs[1], tradar=4)


if __name__ == "__main__":
    P = BC.Part("occ_cad")
    P.kor("storlekar_step_tessellering", del_storlekar)
    P.kor("korrekthet_boolean_sfar", del_korrekthet)
    P.kor("determinism_tessellering", del_determinism)
    P.skriv()
